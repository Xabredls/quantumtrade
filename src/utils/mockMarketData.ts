/**
 * Generates realistic candlestick data for charts & simulations
 */
export function generateCandles(basePrice: number, count: number = 60, volatility: number = 0.008): Candle[] {
  const candles: Candle[] = [];
  let current = basePrice;
  const now = Date.now();
  const stepMs = 5 * 60 * 1000; // 5-minute candles

  for (let i = count; i >= 0; i--) {
    const time = now - i * stepMs;
    // Random walk with mean reversion
    const changePct = (Math.random() - 0.49) * volatility;
    const open = current;
    const close = Number((open * (1 + changePct)).toFixed(basePrice > 100 ? 2 : 5));
    const high = Number((Math.max(open, close) * (1 + Math.random() * volatility * 0.5)).toFixed(basePrice > 100 ? 2 : 5));
    const low = Number((Math.min(open, close) * (1 - Math.random() * volatility * 0.5)).toFixed(basePrice > 100 ? 2 : 5));
    const volume = Math.round(100 + Math.random() * 500);

    candles.push({ time, open, high, low, close, volume });
    current = close;
  }

  return candles;
}
